export const MONACO_VSCODE_DARK_THEME_ID = 'vscode-dark'

export function registerMonacoVscodeDarkTheme(
  monaco: Pick<typeof Monaco, 'editor'>
): void {
  monaco.editor.defineTheme(MONACO_VSCODE_DARK_THEME_ID, {
    base: 'vs-dark',
    inherit: true,
    rules: MONACO_VSCODE_DARK_RULES,
    colors: MONACO_VSCODE_DARK_COLORS
  })
}
